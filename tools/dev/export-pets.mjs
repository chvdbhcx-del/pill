// Regenerates src-tauri/src/ui/pets/data/*.json and data.rs from the web pets (src/pets*.js + pets.css) in a headless Chrome.
//
//   node tools/dev/export-pets.mjs            all pets
//   node tools/dev/export-pets.mjs cat koi    only these ids (data.rs is rebuilt from the files present)
//
// Per pet and per context (state x side x idle flag x reduced motion x look x energy) the page side (pets-export-page.js) reads the computed style
// of every node and the CSS animations the browser starts; the Rust engine replays them. Why JSON + include_bytes! and not generated Rust:
// the files are ~35 KB per pet, parsed with serde_json (already a dependency) only when a pet is selected (< 1 ms), and a diff of the data is readable.
import { mkdirSync, readdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { launch } from './headless.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', '..', 'src-tauri', 'src', 'ui', 'pets');
const dataDir = join(out, 'data');
mkdirSync(dataDir, { recursive: true });

const only = process.argv.slice(2);
const b = await launch();
try {
  await b.call('Page.navigate', { url: pathToFileURL(join(here, 'pets-harness.html')).href });
  await new Promise((r) => setTimeout(r, 1500));
  const ids = await b.evaluate('PetsExport.ids()');
  for (const id of ids) {
    if (only.length && !only.includes(id)) continue;
    const t = Date.now();
    const json = await b.evaluate(`PetsExport.dumpPet(${JSON.stringify(id)}).then((r) => JSON.stringify(r))`, 600000);
    writeFileSync(join(dataDir, `${id}.json`), json);
    console.log(id.padEnd(10), String(json.length).padStart(7), 'bytes', Date.now() - t, 'ms');
  }
  // data.rs: the list of embedded files, in registry order
  const have = new Set(readdirSync(dataDir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)));
  const lines = ids.filter((id) => have.has(id)).map((id) => `    ("${id}", include_bytes!("data/${id}.json")),`);
  writeFileSync(join(out, 'data.rs'), `// GENERATED by tools/dev/export-pets.mjs (node tools/dev/export-pets.mjs). Do not edit.\n// One JSON file per pet: nodes, base styles, per-context patches, keyframe pool. See ui/pets/model.rs for the schema.\n\npub const PETS: &[(&str, &[u8])] = &[\n${lines.join('\n')}\n];\n`);
} finally {
  await b.close();
}
